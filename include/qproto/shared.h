#ifndef QPROTO_SHARED_H
#define QPROTO_SHARED_H

#include <stddef.h>
#include <stdint.h>

/* Game info */
#define MAX_PLAYERS					32
#define HLDS_APPID					10
#define HLDS_APPVERSION				"1.1.2.7/Stdio"

/* Auth constants */
#define STEAM_ID_LAN				0
#define STEAM_ID_PENDING			1
#define MAX_AUTHKEY_LEN				128
#define IPGEN_KEY					0xA95CE2B9 /* qproto_hook.c synthetic-id-by-IP; mirrors classic SteamByIp() */

/* Internal kinds — same {tag}_leaf rule as Authum module-style.md. Public API
 * mirrors these as qproto_auth_kind_* / qproto_key_kind_* in qproto/api.h. */
enum auth_key_kind {
	auth_key_kind_steam,
	auth_key_kind_volumeid,
	auth_key_kind_hddsn,
	auth_key_kind_fileid,
	auth_key_kind_sxeid,
	auth_key_kind_other,
	auth_key_kind_max
};
typedef enum auth_key_kind auth_key_kind_t;

/*
 * Classic ports also had SteamEmu / AVSMP / HLTV enum leaves — not ported:
 * dead formats, or (HLTV) a path that never reaches Steam_NotifyClientConnect.
 */
enum client_auth_kind {
	client_auth_kind_unknown = 0,
	client_auth_kind_no_steam_47,			/* No auth data was provided by client */
	client_auth_kind_no_steam_48,			/* No auth data was provided by client */
	client_auth_kind_setti,				/* Setti bot */
	client_auth_kind_steam,				/* Authorized by steam */
	client_auth_kind_steam_pending,		/* Authorized by steam, but ID is STEAM_ID_PENDING */
	client_auth_kind_old_revemu,			/* Old RevEmu (authorization by serial number of first HDD volume in the system) */
	client_auth_kind_revemu,				/* RevEmu (authorization by serial number of first HDD in the system) */
	client_auth_kind_steamclient_2009,	/* SteamClient (alias for revemu) (authorization by serial number of first HDD in the system) */
	client_auth_kind_revemu_2013,			/* RevEmu (authorization by serial number of first HDD in the system) */
	client_auth_kind_sxei,				/* Authorization by sXe Injected anticheat ID. */
	client_auth_kind_vellum,				/* raspad-revloader steamclient (64-byte VLLM ticket) */

	client_auth_kind_max,
};
typedef enum client_auth_kind client_auth_kind_t;

enum client_id_kind {
	client_id_kind_unknown = 0,
	client_id_kind_real_steam = 1, /* Real STEAM_x:x:x */
	client_id_kind_real_valve = 2, /* Real VALVE_x:x:x */
	client_id_kind_steam_by_ip = 3, /* STEAM_x:x:x generated by client's IP */
	client_id_kind_valve_by_ip = 4, /* VALVE_x:x:x generated by client's IP */
	client_id_kind_deprecated = 5, /* Client having this id kind will be kicked */
	client_id_kind_reserved = 6,
	client_id_kind_hltv = 7, /* HLTV */
	client_id_kind_steam_id_lan = 8,
	client_id_kind_steam_id_pending = 9,
	client_id_kind_valve_id_lan = 10,
	client_id_kind_valve_id_pending = 11,
	client_id_kind_steam_666_88_666 = 12,
	client_id_kind_max = 13,
};
typedef enum client_id_kind client_id_kind_t;

/*
 * Broader auth plugins also expose auth_version, server_answer_type,
 * client_id_gen_opts_t, and ipv4 LAN helpers. qproto does not: we hook a single
 * pinned engine build, and MapClientIdKindToAuthIdType/CidForAuthKind already
 * cover the id-assignment logic we need.
 */

#endif /* QPROTO_SHARED_H */
